"""Public sequential RTL -> explicit D/Q cut -> independent ABC implementation."""
import copy, hashlib, json, os, re, subprocess, time
from pathlib import Path
ROOT=Path(__file__).resolve().parent
S=json.loads((ROOT/'sources.json').read_text())
TOOL=os.environ['CIRCUITFUSION_YOSYS']

def run(script,name):
    (ROOT/'logs').mkdir(exist_ok=True)
    (ROOT/'logs'/f'{name}.ys').write_text(script)
    env=os.environ.copy(); env['YOWASP_CACHE_DIR']=os.environ['CIRCUITFUSION_CACHE']
    with (ROOT/'logs'/f'{name}.log').open('w') as log:
        subprocess.run([TOOL,'-T','-s',f'logs/{name}.ys'],cwd=ROOT,env=env,stdout=log,stderr=subprocess.STDOUT,check=True,timeout=600)

def graph(m):
    nodes=[];edges=[];driver={};cells={}
    for p,v in sorted(m['ports'].items()):
        if v['direction']=='input':
            for lane,bit in enumerate(v['bits']):driver[bit]=len(nodes);nodes.append(['PI_'+p,lane,len(v['bits'])])
    for bit in ['0','1','x','z']:driver[bit]=len(nodes);nodes.append(['CONST_'+bit,0,1])
    word=any(c['type'].startswith('$') and not c['type'].startswith('$_') for c in m['cells'].values())
    for name,c in sorted(m['cells'].items()):
        width=max((len(v) for k,v in c['connections'].items() if c['port_directions'][k]=='output'),default=1)
        cells[name]=len(nodes);nodes.append([c['type'],0,width])
        for p,conn in c['connections'].items():
            if c['port_directions'][p]=='output':
                for lane,bit in enumerate(conn):
                    if word:
                        ix=len(nodes);nodes.append(['OUTPUT_BIT',lane,len(conn)]);edges.append([cells[name],ix,0]);driver[bit]=ix
                    else:driver[bit]=cells[name]
    for name,c in sorted(m['cells'].items()):
        for p,conn in c['connections'].items():
            if c['port_directions'][p]=='input':
                role=0 if p=='A' else 1 if p=='B' else 2
                for lane,bit in enumerate(conn):
                    if word:
                        ix=len(nodes);nodes.append(['PIN_'+p,lane,len(conn)]);edges.extend([[driver[bit],ix,role],[ix,cells[name],role]])
                    else:edges.append([driver[bit],cells[name],role])
    for lane,bit in enumerate(m['ports']['next_state']['bits']):
        ix=len(nodes);nodes.append(['OUTPUT',lane,1]);edges.append([driver[bit],ix,0])
    return dict(nodes=nodes,edges=edges)

def tokens(path):
    s=re.sub(r'/\*.*?\*/|//[^\n]*','',path.read_text(),flags=re.S)
    # Strip source names and autogenerated internal identifiers consistently.
    keep=set('module endmodule input output wire reg signed assign always begin end if else posedge negedge case endcase default'.split())|{'a','b','rst','en','state','next_state','gold'}
    names={}
    def anon(m):
        v=m[0]
        if v in keep:return v
        if v not in names:names[v]='q' if not names else 'tmp'+str(len(names))
        return names[v]
    raw=re.findall(r"\d+'[bdh][0-9a-fA-Fxz]+|\\[^\s]+|[A-Za-z_][A-Za-z_0-9$]*|\d+|<=|==|!=|<<|>>|[^\s]",s)
    return [anon(re.match(r'.*',t)) if re.match(r'[A-Za-z_\\]',t) else t for t in raw]

def main():
    start=time.monotonic();assert hashlib.sha256((ROOT/'PROTOCOL.json').read_bytes()).hexdigest()==(ROOT/'PROTOCOL.sha256').read_text().strip()
    records=[];failures=[];candidates=[]
    for si,source in enumerate(S['sources']):
        sd=ROOT/'data'/f's{si:02d}';sd.mkdir(parents=True,exist_ok=True)
        assert hashlib.sha256((ROOT/'assets'/source['local']).read_bytes()).hexdigest()==source['sha256']
        rel=f'data/s{si:02d}'
        try:run(f"read_verilog assets/{source['local']}\nhierarchy -top {source['top']}\nflatten\nproc\nopt_clean\nwrite_json {rel}/sequential.json\n",f'extract{si:02d}')
        except Exception as e:failures.append(dict(source=si,stage='extract',reason=str(e)));continue
        m=json.loads((sd/'sequential.json').read_text())['modules'][source['top']]
        ff=[(n,c) for n,c in sorted(m['cells'].items()) if c['type']=='$dff']
        other=[c['type'] for c in m['cells'].values() if 'dff' in c['type'] and c['type']!='$dff']
        if other:failures.append(dict(source=si,stage='ff',reason=other));continue
        clocks={b for _,c in ff for b in c['connections']['CLK']}
        for fi,(ffname,target) in enumerate(ff):
            sid=f's{si:02d}_r{fi:02d}';d=ROOT/'data'/sid;d.mkdir(exist_ok=True);rel=f'data/{sid}'
            cm=copy.deepcopy(m);ports={};mapping={};ordinary=0
            for p,v in m['ports'].items():
                if v['direction']!='input' or set(v['bits'])<=clocks:continue
                name='rst' if p.lower() in ['rst','reset'] else 'en' if p.lower()=='en' else ['a','b'][ordinary] if ordinary<2 else f'input_{ordinary}'
                if name not in ['rst','en']:ordinary+=1
                ports[name]=v;mapping[p]=name
            # proc can alias distinct register outputs. One cut input per physical
            # wire is required: duplicated input bits introduce conflicting drivers.
            qbits=list(dict.fromkeys(b for _,c in ff for b in c['connections']['Q'] if isinstance(b,int)))
            ports['state']={'direction':'input','bits':qbits};ports['next_state']={'direction':'output','bits':target['connections']['D']}
            cm['ports']=ports;cm['attributes']={'top':'1'}
            # Original internal net 'state' can collide with our canonical port.
            # Combinational cut graphs retain bit IDs, never initial attributes.
            cm['netnames']={}
            for name,_ in ff:del cm['cells'][name]
            (d/'cut.json').write_text(json.dumps({'modules':{'gold':cm}}))
            script=f'''read_json {rel}/cut.json
hierarchy -top gold
opt_clean -purge
check -assert
write_json {rel}/rtl.json
write_verilog -noattr {rel}/cone.v
design -save rtl
opt
write_json {rel}/equivalent.json
write_verilog -noattr {rel}/equivalent.v
techmap
opt
abc -g AND,OR,XOR,XNOR,MUX
clean
rename gold gate
write_json {rel}/gate.json
write_verilog -noattr {rel}/gate.v
design -copy-from rtl gold
equiv_make gold gate equiv
hierarchy -top equiv
equiv_simple
tee -o {rel}/formal_status.txt equiv_status -assert
'''
            try:
                run(script,sid)
                views={k:graph(next(iter(json.loads((d/f).read_text())['modules'].values()))) for k,f in [('graph','rtl.json'),('equivalent_graph','equivalent.json'),('netlist','gate.json')]}
                code=tokens(d/'cone.v');alt=tokens(d/'equivalent.v');mx=max(len(v['nodes']) for v in views.values());candidate=dict(sample_id=sid,source=si,ff=ffname,graph_nodes=mx,code_tokens=len(code));candidates.append(candidate)
                if mx>1024 or max(len(code),len(alt))>2048:raise ValueError('predeclared size cap')
                status=(d/'formal_status.txt').read_text();assert 'Equivalence successfully proven' in status
                records.append(dict(sample_id=sid,family=source['family'],source=si,register_index=fi,split='test',summary=source['summary'],summary_tokens=re.findall('[a-z]+',source['summary'].lower()),code=code,equivalent_code=alt,targets={'gate_count':len(next(iter(json.loads((d/'gate.json').read_text())['modules'].values()))['cells']),'gate_depth':0},modality_ids={k:sid for k in ['code','summary','graph','netlist']},formal_proved=True,port_map=mapping,**views))
            except Exception as e:failures.append(dict(sample_id=sid,stage='cone',reason=str(e)))
    (ROOT/'manifest.json').write_text(json.dumps(records,indent=2)+'\n');(ROOT/'preparation.json').write_text(json.dumps(dict(accepted=len(records),candidates=candidates,failures=failures,wall_seconds=time.monotonic()-start),indent=2)+'\n')
    print(json.dumps(dict(accepted=len(records),candidates=candidates,failures=failures,wall_seconds=time.monotonic()-start)),flush=True)
if __name__=='__main__':main()
